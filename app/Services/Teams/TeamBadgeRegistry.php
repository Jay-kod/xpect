    /**
     * Resolve official crest URL for a given club name, short name, or alias.
     */
    public static function resolve(?string $name): ?string
    {
        if ($name === null || trim($name) === '') {
            return null;
        }

        $normalized = self::normalize($name);

        if (isset(self::$badges[$normalized])) {
            return self::$badges[$normalized];
        }

        // Try fuzzy token match
        foreach (self::$badges as $key => $url) {
            if ($key === $normalized || str_contains($normalized, $key) || str_contains($key, $normalized)) {
                return $url;
            }
        }

        return null;
    }

    /**
     * Get all registered badges.
     *
     * @return array<string, string>
     */
    public static function all(): array
    {
        return self::$badges;
    }

    /**
     * Normalize a name string for lookup.
     */
    public static function normalize(string $name): string
    {
        $clean = mb_strtolower(trim($name), 'UTF-8');
        // Replace diacritics / accents
        $clean = strtr($clean, [
            'á'=>'a', 'à'=>'a', 'â'=>'a', 'ä'=>'a', 'ã'=>'a', 'å'=>'a',
            'é'=>'e', 'è'=>'e', 'ê'=>'e', 'ë'=>'e',
            'í'=>'i', 'ì'=>'i', 'î'=>'i', 'ï'=>'i',
            'ó'=>'o', 'ò'=>'o', 'ô'=>'o', 'ö'=>'o', 'õ'=>'o',
            'ú'=>'u', 'ù'=>'u', 'û'=>'u', 'ü'=>'u',
            'ñ'=>'n', 'ç'=>'c',
        ]);
        // Strip punctuation
        $clean = (string) preg_replace('/[^a-z0-9 ]+/', ' ', $clean);
        return trim((string) preg_replace('/\s+/', ' ', $clean));
    }
